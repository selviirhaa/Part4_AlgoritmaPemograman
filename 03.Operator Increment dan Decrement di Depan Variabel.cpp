#include <iostream>
using namespace std;

int main()
{
    int a = 10, b = 5;

    cout << "Nilai A = " << a;
    cout << "\nNilai ++A = " << ++a;
    cout << "\nNilai A = " << a;

    cout << "\nNilai B = " << b;
    cout << "\nNilai --B = " << --b;
    cout << "\nNilai B = " << b;

    return 0;
}
